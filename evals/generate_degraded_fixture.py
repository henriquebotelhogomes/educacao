"""
generate_degraded_fixture.py — Reproducible poor-scan fixture generator.

Derives a small subset PDF from the cerrado-goiano source (first n_pages) and
generates synthetic scan-degraded PNG images using Pillow with a fixed seed.

Usage
-----
    python evals/generate_degraded_fixture.py \\
        --source support/ebooks/ph,+Gerente+da+editora,+cerrado-goiano.pdf \\
        --output evals/fixtures/ \\
        --pages 5 \\
        --seed 42

Outputs
-------
    evals/fixtures/cerrado-goiano-scan-fixture-p1-5.pdf   (page subset, provenance preserved)
    evals/fixtures/scan_noise_page_01.png ... _05.png     (synthetic scan-quality images)
    evals/fixtures/fixture_provenance.json                 (provenance record)

Reproducibility guarantee
--------------------------
Given identical --source, --pages, and --seed the outputs are bit-for-bit identical.
The PDF subset depends only on the source file; the PNG images depend on seed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import random
import sys
from datetime import datetime, timezone


def _sha256_file(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate_degraded_fixture(
    source_pdf: pathlib.Path,
    output_dir: pathlib.Path,
    n_pages: int = 5,
    seed: int = 42,
) -> pathlib.Path:
    """Extract the first ``n_pages`` from ``source_pdf`` and write a subset PDF.

    The subset preserves the full content of the source pages (no alteration to
    the PDF content streams), making provenance traceable.  The file is named
    to convey its origin and page range.

    Also calls :func:`generate_scan_noise_images` and writes a provenance JSON
    alongside.

    Returns the path to the output PDF.
    """
    try:
        import pypdf
    except ImportError as exc:
        raise ImportError("pypdf is required: pip install pypdf") from exc

    output_dir = pathlib.Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    reader = pypdf.PdfReader(str(source_pdf))
    n_actual = min(n_pages, len(reader.pages))

    writer = pypdf.PdfWriter()
    for i in range(n_actual):
        writer.add_page(reader.pages[i])

    # Embed metadata so the fixture is self-describing
    source_hash = _sha256_file(source_pdf)
    writer.add_metadata(
        {
            "/Title": f"Scan fixture derived from {source_pdf.name} (pages 1–{n_actual})",
            "/Subject": (
                f"Poor-scan test fixture. Source: {source_pdf.name}. "
                f"Source SHA-256: {source_hash}. Seed: {seed}. "
                f"Generated by evals/generate_degraded_fixture.py."
            ),
            "/Keywords": "fixture,poor_scan,test,derived,cerrado-goiano",
            "/Producer": "generate_degraded_fixture.py (evals/)",
        }
    )

    stem = source_pdf.stem.replace(",", "-").replace("+", "-").replace(" ", "-")
    # normalise repeated dashes
    while "--" in stem:
        stem = stem.replace("--", "-")
    output_pdf = output_dir / f"{stem}-scan-fixture-p1-{n_actual}.pdf"

    with open(output_pdf, "wb") as fh:
        writer.write(fh)

    # Write companion PNG noise images
    generate_scan_noise_images(output_dir=output_dir, n_pages=n_actual, seed=seed)

    # Write provenance record
    provenance = {
        "source_pdf": str(source_pdf),
        "source_sha256": source_hash,
        "n_pages": n_actual,
        "seed": seed,
        "fixture_pdf": output_pdf.name,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "evals/generate_degraded_fixture.py",
        "notes": (
            "This is a test fixture only. It is derived from the source PDF "
            "to simulate poor scan quality in pipeline tests. "
            "The source PDF is authorized for use per user attestation on 2026-08-03. "
            "Any copyright or license statements embedded in the original PDF are "
            "preserved and take precedence."
        ),
    }
    prov_path = output_dir / "fixture_provenance.json"
    prov_path.write_text(json.dumps(provenance, indent=2, ensure_ascii=False), encoding="utf-8")

    return output_pdf


def generate_scan_noise_images(
    output_dir: pathlib.Path,
    n_pages: int = 5,
    seed: int = 42,
) -> list[pathlib.Path]:
    """Generate synthetic scan-degraded PNG images using Pillow.

    Each image simulates a poor-quality scan: off-white background, salt-and-pepper
    noise, and a slight Gaussian blur.  Generation is fully deterministic given
    ``seed``.

    No actual PDF content is rendered — images are synthetic noise fixtures
    intended to test OCR-robustness of the ingestion pipeline.

    Returns a list of output PNG paths.
    """
    try:
        from PIL import Image, ImageFilter
    except ImportError as exc:
        raise ImportError("Pillow is required: pip install Pillow") from exc

    output_dir = pathlib.Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    rng = random.Random(seed)

    # A5-ish size at 72 dpi — small enough to be fast, large enough to be meaningful
    width, height = 420, 595

    output_paths: list[pathlib.Path] = []
    for page_idx in range(n_pages):
        # Each page uses a fresh noise pattern seeded deterministically
        page_seed = rng.randint(0, 2**31 - 1)
        page_rng = random.Random(page_seed)

        # Build noisy background: off-white with per-pixel salt-and-pepper
        pixel_count = width * height
        data = bytearray(
            max(0, min(255, 240 + page_rng.randint(-35, 5))) for _ in range(pixel_count)
        )
        img = Image.frombytes("L", (width, height), bytes(data))

        # Gaussian blur simulates lens/scan softness
        img = img.filter(ImageFilter.GaussianBlur(radius=0.8))

        # Random dark specks (scan dust/defects) — use tobytes/frombytes for speed
        n_specks = page_rng.randint(50, 200)
        raw = bytearray(img.tobytes())
        for _ in range(n_specks):
            x = page_rng.randint(0, width - 1)
            y = page_rng.randint(0, height - 1)
            raw[y * width + x] = page_rng.randint(0, 80)
        img = Image.frombytes("L", (width, height), bytes(raw))

        out_path = output_dir / f"scan_noise_page_{page_idx + 1:02d}.png"
        img.save(out_path, format="PNG", optimize=False)
        output_paths.append(out_path)

    return output_paths


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a reproducible poor-scan fixture from a source PDF.",
    )
    parser.add_argument(
        "--source",
        required=True,
        help="Path to source PDF (cerrado-goiano).",
    )
    parser.add_argument(
        "--output",
        default="evals/fixtures",
        help="Output directory (default: evals/fixtures).",
    )
    parser.add_argument(
        "--pages",
        type=int,
        default=5,
        help="Number of pages to extract (default: 5).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for noise images (default: 42).",
    )

    args = parser.parse_args(argv)
    source = pathlib.Path(args.source)
    if not source.exists():
        print(f"ERROR: source PDF not found: {source}", file=sys.stderr)
        return 1

    output_pdf = generate_degraded_fixture(
        source_pdf=source,
        output_dir=pathlib.Path(args.output),
        n_pages=args.pages,
        seed=args.seed,
    )
    print(f"Fixture PDF written: {output_pdf}")
    print(f"Provenance JSON written: {pathlib.Path(args.output) / 'fixture_provenance.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
